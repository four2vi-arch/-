def write_docx(path, paras, title=None):
    """표준 라이브러리만으로 단순 docx(문단 목록)."""
    W = 'http://schemas.openxmlformats.org/wordprocessingml/2006/main'
    body = ''
    if title:
        body += '<w:p><w:pPr><w:pStyle w:val="Title"/></w:pPr><w:r><w:rPr><w:b/><w:sz w:val="32"/></w:rPr><w:t xml:space="preserve">%s</w:t></w:r></w:p>' % escape(title)
    for p in paras:
        if isinstance(p, list):   # 표
            rows = ''.join('<w:tr>%s</w:tr>' % ''.join('<w:tc><w:p><w:r><w:t xml:space="preserve">%s</w:t></w:r></w:p></w:tc>' % escape(str(c)) for c in r) for r in p)
            body += '<w:tbl><w:tblPr><w:tblStyle w:val="TableGrid"/><w:tblW w:w="0" w:type="auto"/></w:tblPr>%s</w:tbl>' % rows
        else:
            body += '<w:p><w:r><w:t xml:space="preserve">%s</w:t></w:r></w:p>' % escape(p)
    doc = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><w:document xmlns:w="%s"><w:body>%s</w:body></w:document>' % (W, body)
    ct = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
          '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/>'
          '<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>')
    rels = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with zipfile.ZipFile(path, 'w', zipfile.ZIP_DEFLATED) as z:
        z.writestr('[Content_Types].xml', ct); z.writestr('_rels/.rels', rels); z.writestr('word/document.xml', doc)


def write_xlsx(path, sheets):
    wb = openpyxl.Workbook(); wb.remove(wb.active)
    for name, rows in sheets:
        ws = wb.create_sheet(name)
        for r in rows:
            ws.append(list(r))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    wb.save(path)


def write_eml(path, frm, to, subject, body, when):
    m = email.message.EmailMessage()
    m['From'] = frm; m['To'] = to; m['Subject'] = subject; m['Date'] = email.utils.format_datetime(when)
    m.set_content(body)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'wb') as f:
        f.write(m.as_bytes())


def to_pdf(src, out_dir):
    if not shutil.which('soffice'):
        return None
    try:
        subprocess.run(['soffice', '--headless', '--convert-to', 'pdf', '--outdir', out_dir, src], capture_output=True, timeout=120)
        p = os.path.join(out_dir, os.path.splitext(os.path.basename(src))[0] + '.pdf')
        return p if os.path.exists(p) else None
    except Exception:
        return None


